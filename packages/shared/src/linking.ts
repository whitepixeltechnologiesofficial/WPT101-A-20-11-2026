/**
 * WEB-R1.0 — Web-linking + Web-session CONTRACT (TAD §12.1, §7.1, §7.3, §9.5).
 *
 * This file is the single source of truth for every request, response and
 * push-message shape between Web and the backend. Three parties compile
 * against it:
 *   - apps/backend         (BE-6.1: routes/linking.ts, ws/linking-registry.ts)
 *   - packages/api-client  (the only code Web uses to talk to either backend)
 *   - packages/api-client/mock (the WEB-R1.0 mock server)
 * so the mock and the real backend cannot drift apart silently.
 *
 * ANY CHANGE TO A SHAPE HERE MUST BE TOLD TO TEAM CHARLIE (BE-6.1 owners).
 *
 * Transport recap
 *   socket.io server path ............ SOCKET_PATH ("/realtime")
 *   linking channel (no auth) ........ namespace LINKING_SOCKET_NAMESPACE ("/linking")
 *   session channel (JWT auth) ....... default namespace "/" with
 *                                      handshake auth { token, userId, deviceId }
 *   HTTP ............................. `${API_BASE_URL}/api/${API_VERSION}${path}`
 */

// ── Constants ──────────────────────────────────────────────────────────

/** socket.io server PATH (not a namespace) — both servers mount on it. */
export const SOCKET_PATH = "/realtime";

/** Unauthenticated namespace Web uses before it has credentials. */
export const LINKING_SOCKET_NAMESPACE = "/linking";

/** Server-stamped lifetime of a linking token, from the moment it is registered. */
export const LINKING_TOKEN_TTL_MS = 60_000;

/** Bytes of CSPRNG output in a linking token (→ 43 base64url chars). */
export const LINKING_TOKEN_BYTES = 32;

/** Accepted token shape — mirrors the server's cheap plausibility check. */
export const LINKING_TOKEN_PATTERN = /^[A-Za-z0-9_-]{32,256}$/;

export const LINKING_API = {
  /** Phone confirms a scanned QR (phone's access token). */
  scan: "/linking/scan",
  /** Web logs itself off (Web's access token). */
  logoff: "/linking/logoff",
  /** Rotating refresh, shared by every device type. */
  refresh: "/onboarding/refresh",
} as const;

/** Events on the /linking namespace. */
export const LINKING_EVENTS = {
  /** Web → server, with ack. */
  register: "register",
  /** Server → Web: the phone scanned; here are Web's credentials. PUSH, never polled. */
  accountLinked: "accountLinked",
  /** Server → Web: this token's 60s TTL elapsed; show a fresh QR. */
  linkExpired: "linkExpired",
} as const;

/** Events on the authenticated session namespace. */
export const SESSION_EVENTS = {
  /** Server → Web: this session was revoked elsewhere (new phone login, re-link). */
  forceLogout: "force_logout",
  /**
   * Server → Web: the paired phone's reachability changed.
   * INFORMATIONAL ONLY. Web must keep working whatever this says (WEB-R1.4):
   * Web is a full device with its own session, not a mirror of the phone.
   * Optional for the real backend to emit.
   */
  phonePresence: "phone_presence",
} as const;

// ── Linking channel ────────────────────────────────────────────────────

/** Web's public identity keys (TAD §8.6). Private halves never leave the browser. */
export interface LinkingIdentityBundle {
  /** base64 X25519 public key. */
  identityPublicKey: string;
  /** base64 Ed25519 public key. */
  signingPublicKey?: string;
}

/** Web → server `register` payload. `token` is generated BY WEB (TAD §12.1). */
export interface LinkingRegisterRequest extends LinkingIdentityBundle {
  token: string;
}

export type LinkingRegisterError =
  /** Malformed token or missing identityPublicKey. */
  | "INVALID_REGISTRATION"
  /** Token's 60s already elapsed — it can never be registered again. */
  | "TOKEN_EXPIRED"
  /** Token was already used to link — it can never be registered again. */
  | "TOKEN_ALREADY_USED";

export type LinkingRegisterAck =
  | { ok: true; expiresAt: string }
  | { ok: false; error: LinkingRegisterError };

/** `accountLinked` push payload. */
export interface LinkedPayload {
  accessToken: string;
  refreshToken: string;
  userId: string;
  deviceId: string;
  sessionId: string;
}

/** `linkExpired` push payload. */
export interface LinkExpiredPayload {
  reason: "ttl";
}

// ── HTTP: scan ─────────────────────────────────────────────────────────

export interface LinkingScanRequest {
  token: string;
}

export interface LinkingScanResponse {
  ok: true;
  linked: true;
  deviceId: string;
}

/**
 * Scan failures. The three 410 codes are deliberately distinct so the phone
 * can say "QR expired, refresh it" rather than a generic error (edge case
 * on WEB-R1.0 / WEB-R1.3).
 */
export type LinkingScanError =
  | "INVALID_TOKEN" // 400 malformed
  | "TOKEN_EXPIRED" // 410 registered, but its 60s elapsed
  | "TOKEN_ALREADY_USED" // 410 already linked (or a scan is in flight)
  | "TOKEN_UNKNOWN" // 410 never registered
  | "LINK_FAILED"; // 500

// ── HTTP: logoff / refresh ─────────────────────────────────────────────

export interface LinkingLogoffResponse {
  ok: true;
}

export type LinkingLogoffError = "DEVICE_NOT_FOUND" | "NOT_A_WEB_SESSION" | "LOGOFF_FAILED";

export interface RefreshRequest {
  refreshToken: string;
}

/** Rotating: the returned refreshToken REPLACES the one presented. */
export interface RefreshResponse {
  accessToken: string;
  refreshToken: string;
}

export type RefreshError = "INVALID_REFRESH_TOKEN" | "REFRESH_TOKEN_REUSE";

